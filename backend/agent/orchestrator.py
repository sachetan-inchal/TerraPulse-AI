def normalize_markdown_tables(md: str) -> str:
    """
    Sanitize and normalize malformed markdown tables generated by LLMs.
    Ensures standard GitHub Flavored Markdown (GFM) table parsing:
    - Removes trailing quotes/ticks on delimiter lines (|---|---|')
    - Ensures all rows have leading and trailing pipes
    - Pads rows with missing column separators to match header columns
    - Enforces blank lines before and after table blocks
    """
    if not md:
        return md or ""

    lines = md.split("\n")
    result = []
    in_table = False
    table_cols = 0

    for i, line in enumerate(lines):
        trimmed = line.strip()

        # Check for table delimiter: e.g. |---|---| or |:---|:---| or |--|--|'
        is_delimiter = bool(re.match(r"^\|?(\s*:?-{2,}:?\s*\|)+\s*:?-{2,}:?\s*\|?['\"`\s]*$", trimmed)) and ("-" in trimmed)

        if is_delimiter:
            clean_delim = re.sub(r"['\"`\s]+$", "", trimmed).strip()
            if not clean_delim.startswith("|"):
                clean_delim = "| " + clean_delim
            if not clean_delim.endswith("|"):
                clean_delim = clean_delim + " |"

            table_cols = len(re.findall(r"-+", clean_delim))

            if result:
                prev = result[-1].strip()
                if prev.startswith("|"):
                    if not prev.endswith("|"):
                        prev = prev + " |"
                    result[-1] = prev
                if len(result) > 1 and result[-2].strip() != "":
                    result.insert(-1, "")

            result.append(clean_delim)
            in_table = True
            continue

        if trimmed.startswith("|"):
            clean_row = trimmed
            if not clean_row.endswith("|"):
                clean_row = clean_row + " |"

            if in_table and table_cols > 0:
                cell_count = len(re.findall(r"\|", clean_row)) - 1
                if cell_count < table_cols:
                    clean_row = clean_row + ("  |" * (table_cols - cell_count))

            result.append(clean_row)
            continue

        if in_table:
            in_table = False
            table_cols = 0
            if trimmed != "":
                result.append("")

        result.append(line)

    return "\n".join(result)


class ReActAgent:
    def __init__(
        self,
        mcp_manager: Optional[MCPClientManager] = None,
        llm_manager: Optional[LLMManager] = None,
        storage_service: Optional[StorageService] = None,
        max_iterations: int = 7,
        provider_preference: str = "auto"
    ):
        self.mcp_manager = mcp_manager or MCPClientManager()
        self.llm_manager = llm_manager or LLMManager()
        self.storage = storage_service or StorageService()
        self.pollutant_service = PollutantService()
        self.geo_service = GeospatialService()
        self.cause_service = EnvironmentalCauseAnalysisService()
        self.max_iterations = max_iterations
        self.provider_preference = provider_preference

    def _build_tools_description(self, tools_list: List[Dict[str, Any]]) -> str:
        param_hints = {
            "geocode_location": "Parameters: {'location_name': string (e.g. 'Bengaluru', 'Delhi', 'RV College of Engineering')}",
            "reverse_geocode_coordinates": "Parameters: {'latitude': float, 'longitude': float}",
            "create_investigation_buffer": "Parameters: {'latitude': float, 'longitude': float, 'radius_km': float}",
            "find_nearby_emission_sources": "Parameters: {'latitude': float, 'longitude': float, 'radius_km': float}",
            "search_air_quality_locations": "Parameters: {'query': string (e.g. 'Bengaluru'), 'latitude': float, 'longitude': float, 'radius_meters': int (max 25000), 'iso': string (e.g. 'IN'), 'page': int (default 1), 'limit': int (default 25)}",
            "get_station_details": "Parameters: {'station_id': int}",
            "get_station_latest_measurements": "Parameters: {'station_id': int}",
            "search_scientific_publications": "Parameters: {'query': string (e.g. 'PM2.5 health effects'), 'limit': int}",
            "verify_publication_doi": "Parameters: {'doi': string}",
            "search_wikipedia": "Parameters: {'query': string (e.g. 'Bengaluru geography', 'Air pollution in India'), 'limit': int}",
            "get_wikipedia_summary": "Parameters: {'title': string}",
            "get_pollutant_intelligence": "Parameters: {'pollutant_name': string (e.g. 'PM2.5', 'O3', 'NO2')}",
            "analyze_environmental_causes": "Parameters: {'location': string, 'measurements': list, 'reported_observations': list}"
        }
        lines = []
        for t in tools_list:
            hint = param_hints.get(t['name'], "")
            desc = t['description']
            if hint:
                lines.append(f"- {t['name']}: {desc} {hint}")
            else:
                lines.append(f"- {t['name']}: {desc}")
        lines.append(f"- get_pollutant_intelligence: Retrieve chemical and health profiles for pollutants. {param_hints['get_pollutant_intelligence']}")
        lines.append(f"- analyze_environmental_causes: Evaluate environmental measurements and hypotheses with strict medical disclaimer. {param_hints['analyze_environmental_causes']}")
        return "\n".join(lines)

    def _normalize_tool_arguments(self, tool_name: str, args: Dict[str, Any]) -> Dict[str, Any]:
        normalized = dict(args)
        if tool_name == "geocode_location":
            if "location" in normalized and "location_name" not in normalized:
                normalized["location_name"] = normalized["location"]
            elif "place" in normalized and "location_name" not in normalized:
                normalized["location_name"] = normalized["place"]
            elif "city" in normalized and "location_name" not in normalized:
                normalized["location_name"] = normalized["city"]
            elif "query" in normalized and "location_name" not in normalized:
                normalized["location_name"] = normalized["query"]
            elif "address" in normalized and "location_name" not in normalized:
                normalized["location_name"] = normalized["address"]

        elif tool_name == "search_air_quality_locations":
            if "country" in normalized and "iso" not in normalized:
                normalized["iso"] = normalized["country"]
            if "country_code" in normalized and "iso" not in normalized:
                normalized["iso"] = normalized["country_code"]
            if "location" in normalized and "query" not in normalized:
                normalized["query"] = normalized["location"]
            elif "location_name" in normalized and "query" not in normalized:
                normalized["query"] = normalized["location_name"]
            elif "city" in normalized and "query" not in normalized:
                normalized["query"] = normalized["city"]
            if "radius_meters" in normalized:
                try:
                    normalized["radius_meters"] = min(int(normalized["radius_meters"]), 25000)
                except Exception:
                    normalized["radius_meters"] = 25000
            if "page" in normalized:
                try:
                    normalized["page"] = max(int(normalized["page"]), 1)
                except Exception:
                    normalized["page"] = 1
            if "limit" in normalized:
                try:
                    normalized["limit"] = min(max(int(normalized["limit"]), 1), 100)
                except Exception:
                    normalized["limit"] = 25

        elif tool_name in ("get_station_details", "get_station_latest_measurements"):
            if "id" in normalized and "station_id" not in normalized:
                normalized["station_id"] = normalized["id"]

        elif tool_name == "search_wikipedia":
            if "term" in normalized and "query" not in normalized:
                normalized["query"] = normalized["term"]
            elif "topic" in normalized and "query" not in normalized:
                normalized["query"] = normalized["topic"]

        elif tool_name == "get_wikipedia_summary":
            if "query" in normalized and "title" not in normalized:
                normalized["title"] = normalized["query"]
            elif "article" in normalized and "title" not in normalized:
                normalized["title"] = normalized["article"]

        elif tool_name == "get_pollutant_intelligence":
            if "pollutant" in normalized and "pollutant_name" not in normalized:
                normalized["pollutant_name"] = normalized["pollutant"]
            elif "name" in normalized and "pollutant_name" not in normalized:
                normalized["pollutant_name"] = normalized["name"]
            elif "code" in normalized and "pollutant_name" not in normalized:
                normalized["pollutant_name"] = normalized["code"]

        elif tool_name == "analyze_environmental_causes":
            if "city" in normalized and "location" not in normalized:
                normalized["location"] = normalized["city"]
            if "observations" in normalized and "reported_observations" not in normalized:
                normalized["reported_observations"] = normalized["observations"]

        return normalized

    async def run(self, user_prompt: str, provider_preference: Optional[str] = None) -> AgentRunResult:
        run_id = f"RUN_{uuid.uuid4().hex[:10].upper()}"
        start_time = time.perf_counter()
        events: List[AgentExecutionEvent] = []
        tools_called: List[str] = []
        collected_stations: List[Dict[str, Any]] = []
        buffer_holder: List[Any] = [None]
        collected_sources: List[Any] = []
        collected_reference_points: List[Dict[str, Any]] = []
        collected_citations: List[Dict[str, Any]] = []

        active_preference = provider_preference or self.provider_preference

        # 1. Log USER_REQUEST
        self._record_event(
            events,
            run_id=run_id,
            component="AgentOrchestrator",
            event_type="USER_REQUEST",
            input_data={"prompt": user_prompt, "provider_requested": active_preference},
            status="INFO"
        )

        # 2. Discover MCP tools and format system instructions
        await self.mcp_manager.initialize()
        tools_list = await self.mcp_manager.list_tools()
        allowlist = set(self.mcp_manager._tool_to_server_map.keys())
        allowlist.add("get_pollutant_intelligence")
        allowlist.add("analyze_environmental_causes")

        tools_description = self._build_tools_description(tools_list)
        system_content = REACT_SYSTEM_PROMPT.format(tools_description=tools_description)

        scope_info = GeographicScopeAnalyzer.analyze(user_prompt)
        briefing = (
            f"Investigate the following request: {user_prompt}\n\n"
            f"[INVESTIGATION BRIEFING & OPERATIONAL BOUNDARIES]\n"
            f"- Target Scope: {scope_info['scope_type']} ({scope_info['target_name'] or 'Unspecified'})\n"
            f"- Primary Objective: {scope_info['objective_type']}\n"
            f"- Boundary Assessment: {scope_info['tool_compatibility_note']}\n"
            f"- Operational Rule: {scope_info['strict_rule']}"
        )

        messages = [
            {"role": "system", "content": system_content},
            {"role": "user", "content": briefing}
        ]

        llm, provider_name = self.llm_manager.get_provider(active_preference)
        self._record_event(
            events,
            run_id=run_id,
            component=provider_name,
            event_type="LLM_REQUEST",
            input_data={"active_provider": provider_name, "tools_available": len(allowlist)},
            status="INFO"
        )

        recent_calls: List[Tuple[str, str]] = []  # For repeated-call prevention
        final_answer = ""
        iterations = 0

        while iterations < self.max_iterations:
            iterations += 1
            step_start = time.perf_counter()

            try:
                llm_response: LLMResponse = llm.generate(messages)
            except Exception as e:
                # If cloud quota/rate limit error, attempt automatic failover to alternative provider
                err_text = str(e)
                failover_attempted = False
                if "gemini" in provider_name.lower():
                    try:
                        llm, provider_name = self.llm_manager.get_provider("ollama")
                        self._record_event(
                            events,
                            run_id=run_id,
                            component=provider_name,
                            event_type="RETRY",
                            input_data={"failover": "Cloud rate-limit/quota encountered; automatically failed over to local Ollama (granite4.2:3b)"},
                            status="WARNING"
                        )
                        llm_response = llm.generate(messages)
                        failover_attempted = True
                    except Exception:
                        pass
                elif "ollama" in provider_name.lower():
                    try:
                        llm, provider_name = self.llm_manager.get_provider("gemini")
                        self._record_event(
                            events,
                            run_id=run_id,
                            component=provider_name,
                            event_type="RETRY",
                            input_data={"failover": "Local model failed; automatically failed over to Gemini"},
                            status="WARNING"
                        )
                        llm_response = llm.generate(messages)
                        failover_attempted = True
                    except Exception:
                        pass

                if not failover_attempted:
                    self._record_event(
                        events,
                        run_id=run_id,
                        component=provider_name,
                        event_type="TOOL_EXECUTION_ERROR",
                        error_details=f"LLM Generation failure: {err_text}",
                        status="ERROR"
                    )
                    final_answer = (
                        f"Investigation encountered provider limit: {err_text}. "
                        "Tip: You can switch to 'Ollama (Local Granite 4.2:3b)' using the model switcher at the top of the chat to run 100% offline without rate limits."
                    )
                    break

            # Handle FINAL answer
            if llm_response.type == "final":
                final_answer = normalize_markdown_tables(llm_response.content or "Investigation concluded.")
                self._record_event(
                    events,
                    run_id=run_id,
                    component="AgentOrchestrator",
                    event_type="FINAL_RESPONSE",
                    output_data={"answer_preview": final_answer[:200]},
                    duration_ms=round((time.perf_counter() - step_start) * 1000.0, 2),
                    status="SUCCESS"
                )
                break

            # Handle TOOL_CALL
            tool_name = llm_response.tool_name
            tool_args = self._normalize_tool_arguments(tool_name, llm_response.arguments or {})

            self._record_event(
                events,
                run_id=run_id,
                component="AgentOrchestrator",
                event_type="TOOL_SELECTION",
                input_data={"selected_tool": tool_name, "arguments": tool_args},
                status="INFO"
            )

            # Tool allowlist verification
            if tool_name not in allowlist:
                observation = f"ERROR: Tool '{tool_name}' is not in the authorized tools list."
                self._record_event(
                    events,
                    run_id=run_id,
                    component="AgentOrchestrator",
                    event_type="TOOL_EXECUTION_ERROR",
                    error_details=observation,
                    status="WARNING"
                )
                messages.append({"role": "assistant", "content": json.dumps({"action": tool_name, "arguments": tool_args})})
                messages.append({"role": "user", "content": f"Observation: {observation}"})
                continue

            # Repeated call loop prevention
            call_signature = (tool_name, json.dumps(tool_args, sort_keys=True))
            if recent_calls.count(call_signature) >= 2:
                observation = f"NOTICE: Tool '{tool_name}' with these exact arguments was already executed. Do not repeat; synthesize findings."
                messages.append({"role": "assistant", "content": json.dumps({"action": tool_name, "arguments": tool_args})})
                messages.append({"role": "user", "content": f"Observation: {observation}"})
                continue
            recent_calls.append(call_signature)

            # Execute actual tool
            tool_exec_start = time.perf_counter()
            self._record_event(
                events,
                run_id=run_id,
                component=tool_name,
                event_type="TOOL_EXECUTION_START",
                input_data=tool_args,
                status="INFO"
            )

            tool_res_str = ""
            try:
                if tool_name == "get_pollutant_intelligence":
                    p_name = tool_args.get("pollutant_name") or tool_args.get("pollutant") or "PM2.5"
                    p_prof = self.pollutant_service.get_pollutant_profile(p_name)
                    tool_res_str = json.dumps(p_prof.model_dump(), default=str)
                elif tool_name == "analyze_environmental_causes":
                    loc = tool_args.get("location")
                    meas = tool_args.get("measurements", [])
                    obs = tool_args.get("reported_observations", [])
                    res = self.cause_service.analyze(location=loc, measurements=meas, reported_observations=obs)
                    tool_res_str = json.dumps(res.model_dump(), default=str)
                else:
                    # Execute MCP tool
                    mcp_res = await self.mcp_manager.call_tool(tool_name, tool_args)
                    if mcp_res.get("raw_text"):
                        tool_res_str = mcp_res.get("raw_text")
                    elif mcp_res.get("error"):
                        tool_res_str = json.dumps({"error": mcp_res.get("error")})
                    elif mcp_res.get("data") is not None:
                        tool_res_str = json.dumps(mcp_res.get("data"), default=str)
                    else:
                        tool_res_str = json.dumps({"status": "no data returned"})

                tools_called.append(tool_name)
                dur_ms = round((time.perf_counter() - tool_exec_start) * 1000.0, 2)

                self._record_event(
                    events,
                    run_id=run_id,
                    component=tool_name,
                    event_type="TOOL_EXECUTION_SUCCESS",
                    output_data={"result_preview": tool_res_str[:250]},
                    duration_ms=dur_ms,
                    status="SUCCESS"
                )

                # Collect spatial artifacts and research artifacts for the map / UI
                self._harvest_artifacts(
                    tool_name,
                    tool_args,
                    tool_res_str,
                    collected_stations,
                    buffer_holder,
                    collected_sources,
                    collected_reference_points,
                    collected_citations
                )

            except Exception as e:
                dur_ms = round((time.perf_counter() - tool_exec_start) * 1000.0, 2)
                tool_res_str = json.dumps({"error": f"Tool execution failed: {str(e)}"})
                self._record_event(
                    events,
                    run_id=run_id,
                    component=tool_name,
                    event_type="TOOL_EXECUTION_ERROR",
                    error_details=str(e),
                    duration_ms=dur_ms,
                    status="ERROR"
                )

            # Intermediate Evidence Synthesis & Autonomous Stopping Evaluation
            obs_eval = self._generate_observation_evaluation(
                tool_name=tool_name,
                tool_args=tool_args,
                tool_res_str=tool_res_str,
                scope_info=scope_info,
                tools_called=tools_called
            )

            synthesis = self._evaluate_evidence_synthesis(
                collected_stations=collected_stations,
                collected_buffer_holder=buffer_holder,
                collected_sources=collected_sources,
                collected_reference_points=collected_reference_points,
                collected_citations=collected_citations,
                tools_called=tools_called,
                scope_info=scope_info
            )

            guidance_str = f"Evidence Synthesis Status: {synthesis['guidance']}"

            # Feed observation, critical evaluation, and synthesis guidance back to agent
            messages.append({"role": "assistant", "content": json.dumps({"action": tool_name, "arguments": tool_args})})
            messages.append({"role": "user", "content": f"Observation: {tool_res_str}\n\n{obs_eval}\n\n{guidance_str}"})

        # Check if max iterations reached without final answer
        if not final_answer:
            # Request one final synthesis with gathered observations
            messages.append({
                "role": "user",
                "content": "Iteration limit reached. Please provide your Final Answer synthesizing all observations collected above."
            })
            try:
                final_resp = llm.generate(messages)
                final_answer = normalize_markdown_tables(final_resp.content or "Final synthesis completed.")
            except Exception as e:
                final_answer = f"Completed investigation with observations. Notice: {str(e)}"

        total_dur = round((time.perf_counter() - start_time) * 1000.0, 2)

        # Build GeoJSON map from collected items
        map_collection = self.geo_service.build_geojson_map(
            stations=collected_stations,
            buffer_zone=buffer_holder[0],
            emission_sources=collected_sources,
            reference_points=collected_reference_points
        )

        result = AgentRunResult(
            run_id=run_id,
            user_prompt=user_prompt,
            final_answer=final_answer,
            iterations=iterations,
            total_duration_ms=total_dur,
            events=events,
            tools_called=tools_called,
            map_features=map_collection.model_dump(),
            research_citations=collected_citations,
            confidence_assessment="Evidence gathered and synthesized using authentic data sources."
        )

        # Persist trace
        try:
            self.storage.save_agent_trace(run_id, result.model_dump())
        except Exception:
            pass

        return result

    async def run_stream(self, user_prompt: str, provider_preference: Optional[str] = None):
        """
        Execute ReAct agent with live real-time Server-Sent Events (SSE).
        Yields immediately on tool calls, tool results, spatial updates, and tokens.
        """
        run_id = f"RUN_{uuid.uuid4().hex[:10].upper()}"
        start_time = time.perf_counter()
        events: List[AgentExecutionEvent] = []
        tools_called: List[str] = []
        collected_stations: List[Dict[str, Any]] = []
        buffer_holder: List[Any] = [None]
        collected_sources: List[Any] = []
        collected_reference_points: List[Dict[str, Any]] = []
        collected_citations: List[Dict[str, Any]] = []

        active_preference = provider_preference or self.provider_preference

        yield {
            "type": "start",
            "run_id": run_id,
            "prompt": user_prompt,
            "provider": active_preference
        }

        # 1. Log USER_REQUEST
        self._record_event(
            events,
            run_id=run_id,
            component="AgentOrchestrator",
            event_type="USER_REQUEST",
            input_data={"prompt": user_prompt, "provider_requested": active_preference},
            status="INFO"
        )

        yield {
            "type": "status",
            "message": "Discovering registered MCP tools (OpenAQ, Crossref, Shapely)..."
        }

        # 2. Discover MCP tools and format system instructions
        await self.mcp_manager.initialize()
        tools_list = await self.mcp_manager.list_tools()
        allowlist = set(self.mcp_manager._tool_to_server_map.keys())
        allowlist.add("get_pollutant_intelligence")
        allowlist.add("analyze_environmental_causes")

        tools_description = self._build_tools_description(tools_list)
        system_content = REACT_SYSTEM_PROMPT.format(tools_description=tools_description)

        scope_info = GeographicScopeAnalyzer.analyze(user_prompt)
        briefing = (
            f"Investigate the following request: {user_prompt}\n\n"
            f"[INVESTIGATION BRIEFING & OPERATIONAL BOUNDARIES]\n"
            f"- Target Scope: {scope_info['scope_type']} ({scope_info['target_name'] or 'Unspecified'})\n"
            f"- Primary Objective: {scope_info['objective_type']}\n"
            f"- Boundary Assessment: {scope_info['tool_compatibility_note']}\n"
            f"- Operational Rule: {scope_info['strict_rule']}"
        )

        messages = [
            {"role": "system", "content": system_content},
            {"role": "user", "content": briefing}
        ]

        llm, provider_name = self.llm_manager.get_provider(active_preference)
        self._record_event(
            events,
            run_id=run_id,
            component=provider_name,
            event_type="LLM_REQUEST",
            input_data={"active_provider": provider_name, "tools_available": len(allowlist)},
            status="INFO"
        )

        yield {
            "type": "status",
            "message": f"Connected to {provider_name}. Formulating investigation plan..."
        }

        recent_calls: List[Tuple[str, str]] = []
        final_answer = ""
        iterations = 0

        while iterations < self.max_iterations:
            iterations += 1
            step_start = time.perf_counter()

            accumulated_text = ""

            try:
                # Live token streaming generator for current step
                async def _consume_stream(provider_llm):
                    nonlocal accumulated_text
                    stream_iter = provider_llm.generate_stream(messages)
                    for chunk in stream_iter:
                        if isinstance(chunk, dict):
                            c_type = chunk.get("type", "content")
                            txt = chunk.get("text", "")
                        else:
                            c_type = "content"
                            txt = str(chunk)

                        if not txt:
                            continue

                        if c_type == "content":
                            accumulated_text += txt

                        # Stream every single reasoning/action token live into the Reasoning accordion
                        yield {
                            "type": "thought_token",
                            "content": txt,
                            "iteration": iterations
                        }
                        await asyncio.sleep(0)

                async for evt in _consume_stream(llm):
                    yield evt

                llm_response: LLMResponse = llm._parse_llm_output(accumulated_text)

            except Exception as e:
                # Automatic failover logic
                err_text = str(e)
                failover_attempted = False
                if "gemini" in provider_name.lower():
                    try:
                        llm, provider_name = self.llm_manager.get_provider("ollama")
                        yield {
                            "type": "status",
                            "message": "Cloud quota/rate limit encountered; automatically failed over to local Ollama (granite4.2:3b)..."
                        }
                        self._record_event(
                            events,
                            run_id=run_id,
                            component=provider_name,
                            event_type="RETRY",
                            input_data={"failover": "Switched to local Ollama"},
                            status="WARNING"
                        )
                        accumulated_text = ""
                        async for evt in _consume_stream(llm):
                            yield evt
                        llm_response = llm._parse_llm_output(accumulated_text)
                        failover_attempted = True
                    except Exception:
                        pass

                if not failover_attempted:
                    final_answer = (
                        f"Investigation halted due to provider limit: {err_text}. "
                        "Switch to 'Ollama Local (granite4.2:3b)' in the AI Model dropdown above to run offline with zero rate limits."
                    )
                    yield {"type": "token", "content": final_answer}
                    break

            # Handle FINAL answer
            if llm_response.type == "final":
                final_answer = normalize_markdown_tables(llm_response.content or "Investigation concluded.")
                self._record_event(
                    events,
                    run_id=run_id,
                    component="AgentOrchestrator",
                    event_type="FINAL_RESPONSE",
                    output_data={"answer_preview": final_answer[:200]},
                    duration_ms=round((time.perf_counter() - step_start) * 1000.0, 2),
                    status="SUCCESS"
                )

                yield {
                    "type": "status",
                    "message": "Synthesizing evidence-backed findings..."
                }

                # Stream the clean, parsed final synthesized answer into the main chat bubble
                words = re.split(r'(\s+)', final_answer)
                chunk_batch = ""
                for idx, w in enumerate(words):
                    chunk_batch += w
                    if len(chunk_batch) >= 12 or idx == len(words) - 1:
                        yield {"type": "token", "content": chunk_batch}
                        chunk_batch = ""
                        await asyncio.sleep(0.01)

                break

            # Handle TOOL_CALL
            tool_name = llm_response.tool_name
            tool_args = self._normalize_tool_arguments(tool_name, llm_response.arguments or {})

            # Immediately yield tool_start to UI
            yield {
                "type": "tool_start",
                "tool_name": tool_name,
                "arguments": tool_args,
                "iteration": iterations
            }

            self._record_event(
                events,
                run_id=run_id,
                component="AgentOrchestrator",
                event_type="TOOL_SELECTION",
                input_data={"selected_tool": tool_name, "arguments": tool_args},
                status="INFO"
            )

            # Check allowlist
            if tool_name not in allowlist:
                observation = f"ERROR: Tool '{tool_name}' is not in authorized tools list."
                yield {
                    "type": "tool_done",
                    "tool_name": tool_name,
                    "duration_ms": 0,
                    "error": observation,
                    "preview": observation
                }
                messages.append({"role": "assistant", "content": json.dumps({"action": tool_name, "arguments": tool_args})})
                messages.append({"role": "user", "content": f"Observation: {observation}"})
                continue

            # Repeated call loop prevention
            call_signature = (tool_name, json.dumps(tool_args, sort_keys=True))
            if recent_calls.count(call_signature) >= 2:
                observation = f"NOTICE: Tool '{tool_name}' already executed. Synthesizing findings."
                yield {
                    "type": "tool_done",
                    "tool_name": tool_name,
                    "duration_ms": 0,
                    "preview": observation
                }
                messages.append({"role": "assistant", "content": json.dumps({"action": tool_name, "arguments": tool_args})})
                messages.append({"role": "user", "content": f"Observation: {observation}"})
                continue
            recent_calls.append(call_signature)

            # Execute actual tool
            tool_exec_start = time.perf_counter()
            self._record_event(
                events,
                run_id=run_id,
                component=tool_name,
                event_type="TOOL_EXECUTION_START",
                input_data=tool_args,
                status="INFO"
            )

            tool_res_str = ""
            parsed_data = None
            try:
                if tool_name == "get_pollutant_intelligence":
                    p_name = tool_args.get("pollutant_name") or tool_args.get("pollutant") or "PM2.5"
                    p_prof = self.pollutant_service.get_pollutant_profile(p_name)
                    tool_res_str = json.dumps(p_prof.model_dump(), default=str)
                    parsed_data = p_prof.model_dump()
                elif tool_name == "analyze_environmental_causes":
                    loc = tool_args.get("location")
                    meas = tool_args.get("measurements", [])
                    obs = tool_args.get("reported_observations", [])
                    res = self.cause_service.analyze(location=loc, measurements=meas, reported_observations=obs)
                    tool_res_str = json.dumps(res.model_dump(), default=str)
                    parsed_data = res.model_dump()
                else:
                    mcp_res = await self.mcp_manager.call_tool(tool_name, tool_args)
                    if mcp_res.get("raw_text"):
                        tool_res_str = mcp_res.get("raw_text")
                    elif mcp_res.get("error"):
                        tool_res_str = json.dumps({"error": mcp_res.get("error")})
                    elif mcp_res.get("data") is not None:
                        tool_res_str = json.dumps(mcp_res.get("data"), default=str)
                    else:
                        tool_res_str = json.dumps({"status": "no data returned"})
                    parsed_data = mcp_res.get("data")

                tools_called.append(tool_name)
                dur_ms = round((time.perf_counter() - tool_exec_start) * 1000.0, 2)

                self._record_event(
                    events,
                    run_id=run_id,
                    component=tool_name,
                    event_type="TOOL_EXECUTION_SUCCESS",
                    output_data={"result_preview": tool_res_str[:250]},
                    duration_ms=dur_ms,
                    status="SUCCESS"
                )

                # Harvest artifacts for map and citations
                prev_station_count = len(collected_stations)
                prev_citation_count = len(collected_citations)
                self._harvest_artifacts(
                    tool_name,
                    tool_args,
                    tool_res_str,
                    collected_stations,
                    buffer_holder,
                    collected_sources,
                    collected_reference_points,
                    collected_citations
                )

                # Immediately yield tool_done event
                yield {
                    "type": "tool_done",
                    "tool_name": tool_name,
                    "duration_ms": dur_ms,
                    "preview": tool_res_str[:300],
                    "data": parsed_data
                }

                # Observation evaluation and evidence synthesis
                obs_eval = self._generate_observation_evaluation(
                    tool_name=tool_name,
                    tool_args=tool_args,
                    tool_res_str=tool_res_str,
                    scope_info=scope_info,
                    tools_called=tools_called
                )

                yield {
                    "type": "observation_evaluation",
                    "tool_name": tool_name,
                    "evaluation": obs_eval
                }

                # Evaluate intermediate evidence synthesis
                synthesis = self._evaluate_evidence_synthesis(
                    collected_stations=collected_stations,
                    collected_buffer_holder=buffer_holder,
                    collected_sources=collected_sources,
                    collected_reference_points=collected_reference_points,
                    collected_citations=collected_citations,
                    tools_called=tools_called,
                    scope_info=scope_info
                )

                # Emit live evidence synthesis update
                yield {
                    "type": "evidence_synthesis",
                    "iteration": iterations,
                    "synthesis": synthesis
                }

                # If map features updated, yield map_update immediately!
                if len(collected_stations) > prev_station_count or len(collected_reference_points) > 0 or buffer_holder[0] is not None or len(collected_sources) > 0:
                    current_map = self.geo_service.build_geojson_map(
                        stations=collected_stations,
                        buffer_zone=buffer_holder[0],
                        emission_sources=collected_sources,
                        reference_points=collected_reference_points
                    )
                    yield {
                        "type": "map_update",
                        "map_features": current_map.model_dump()
                    }

                # If citations updated, yield citations_update immediately!
                if len(collected_citations) > prev_citation_count:
                    yield {
                        "type": "citations_update",
                        "citations": collected_citations
                    }

            except Exception as e:
                dur_ms = round((time.perf_counter() - tool_exec_start) * 1000.0, 2)
                tool_res_str = json.dumps({"error": f"Tool execution failed: {str(e)}"})
                obs_eval = f"[Observation Evaluation - Tool Failure] Execution of '{tool_name}' failed: {str(e)}. Attempt fallback or report honestly."
                yield {
                    "type": "tool_done",
                    "tool_name": tool_name,
                    "duration_ms": dur_ms,
                    "error": str(e),
                    "preview": tool_res_str
                }
                synthesis = self._evaluate_evidence_synthesis(
                    collected_stations=collected_stations,
                    collected_buffer_holder=buffer_holder,
                    collected_sources=collected_sources,
                    collected_reference_points=collected_reference_points,
                    collected_citations=collected_citations,
                    tools_called=tools_called,
                    scope_info=scope_info
                )

            guidance_str = f"Evidence Synthesis Status: {synthesis['guidance']}"

            messages.append({"role": "assistant", "content": json.dumps({"action": tool_name, "arguments": tool_args})})
            messages.append({"role": "user", "content": f"Observation: {tool_res_str}\n\n{obs_eval}\n\n{guidance_str}"})

        # Final map collection
        map_collection = self.geo_service.build_geojson_map(
            stations=collected_stations,
            buffer_zone=buffer_holder[0],
            emission_sources=collected_sources,
            reference_points=collected_reference_points
        )

        total_dur = round((time.perf_counter() - start_time) * 1000.0, 2)
        final_result = AgentRunResult(
            run_id=run_id,
            user_prompt=user_prompt,
            final_answer=final_answer,
            iterations=iterations,
            total_duration_ms=total_dur,
            events=events,
            tools_called=tools_called,
            map_features=map_collection.model_dump(),
            research_citations=collected_citations,
            confidence_assessment="Evidence gathered and synthesized using authentic data sources."
        )

        try:
            self.storage.save_agent_trace(run_id, final_result.model_dump())
        except Exception:
            pass

        # Yield completion done event
        yield {
            "type": "done",
            "run_id": run_id,
            "final_answer": final_answer,
            "tools_called": tools_called,
            "iterations": iterations,
            "total_duration_ms": total_dur,
            "map_features": map_collection.model_dump(),
            "citations": collected_citations,
            "events": [e.model_dump() for e in events]
        }

    def _record_event(
        self,
        events: List[AgentExecutionEvent],
        run_id: str,
        component: str,
        event_type: str,
        input_data: Optional[Dict[str, Any]] = None,
        output_data: Optional[Dict[str, Any]] = None,
        duration_ms: Optional[float] = None,
        status: str = "INFO",
        error_details: Optional[str] = None
    ):
        event = AgentExecutionEvent(
            event_id=f"EVT_{uuid.uuid4().hex[:8].upper()}",
            timestamp=datetime.now(timezone.utc).isoformat(),
            component=component,
            event_type=event_type,
            input_data=input_data,
            output_data=output_data,
            duration_ms=duration_ms,
            status=status,
            error_details=error_details
        )
        events.append(event)

    def _generate_observation_evaluation(
        self,
        tool_name: str,
        tool_args: Dict[str, Any],
        tool_res_str: str,
        scope_info: Optional[Dict[str, Any]] = None,
        tools_called: Optional[List[str]] = None
    ) -> str:
        """
        Critically evaluate observation immediately following tool execution.
        Distinguishes verified facts, candidate sources, estimates, and data limits.
        """
        data = None
        try:
            data = json.loads(tool_res_str)
        except Exception:
            pass

        eval_lines = []

        if isinstance(data, dict) and "error" in data:
            err_msg = data["error"]
            eval_lines.append(f"[Observation Evaluation - Tool Error] Error from '{tool_name}': {err_msg}")
            eval_lines.append("Strategy Recommendation: Examine parameters or evaluate whether an alternative tool (such as Wikipedia or scientific publication search) is available as a fallback rather than repeating the same failed query.")
            return "\n".join(eval_lines)

        if tool_name == "find_nearby_emission_sources":
            sources = data if isinstance(data, list) else (data.get("sources", []) if isinstance(data, dict) else [])
            rad = tool_args.get("radius_km", 10.0)
            if len(sources) == 0:
                eval_lines.append(f"[Observation Evaluation - Empty Sources Result] 0 candidate emission facilities returned within radius {rad} km.")
                eval_lines.append("CRITICAL: An empty database result DOES NOT prove that no emission sources exist. It only indicates no matching industrial features are indexed in OpenStreetMap Overpass within this radius.")
                eval_lines.append("Strategy: Consider expanding radius, investigating alternative coordinates, or reporting that no registered industrial sources were detected within the searched radius.")
            else:
                eval_lines.append(f"[Observation Evaluation - Candidate Sources Found] {len(sources)} industrial/power facility/facilities located via Overpass API.")
                eval_lines.append("What this establishes: Candidate point-source facilities exist at these coordinates.")
                eval_lines.append("What this does NOT establish: Geographic proximity DOES NOT prove causation. These are unverified candidate facilities until stack emissions or dispersion plumes are measured.")

        elif tool_name == "search_air_quality_locations":
            stations = []
            if isinstance(data, dict):
                stations = data.get("stations", [])
            elif isinstance(data, list):
                stations = data
            if len(stations) == 0:
                eval_lines.append("[Observation Evaluation - No Monitoring Stations] 0 active OpenAQ stations found within search parameters.")
                eval_lines.append("What this establishes: No station in the OpenAQ network matches this query/radius.")
                eval_lines.append("Strategy: Do not fabricate air quality readings; if measurements are unavailable, state INCONCLUSIVE.")
            else:
                eval_lines.append(f"[Observation Evaluation - Monitoring Stations Discovered] {len(stations)} stations returned from OpenAQ.")
                eval_lines.append("CRITICAL: Ambient monitoring stations are NOT emission sources. They measure ambient air, not stack emissions.")
                eval_lines.append("Note: Station metadata does NOT include current measurements until 'get_station_latest_measurements' is executed.")

        elif tool_name == "get_station_latest_measurements":
            measurements = data.get("measurements", []) if isinstance(data, dict) else []
            if len(measurements) == 0:
                eval_lines.append("[Observation Evaluation - No Station Measurements] Station has 0 current sensor readings.")
                eval_lines.append("What this establishes: Sensor hardware may be offline or not reporting.")
                eval_lines.append("Strategy: Query another nearby station or check historical hourly data; do not invent readings.")
            else:
                stale_count = sum(1 for m in measurements if m.get("is_stale", False))
                eval_lines.append(f"[Observation Evaluation - Latest Measurements] {len(measurements)} parameter reading(s) retrieved.")
                if stale_count > 0:
                    eval_lines.append(f"WARNING: {stale_count} reading(s) are STALE (>24 hours old). Must be disclosed honestly as historical or stale.")
                eval_lines.append("What this establishes: Ambient concentration at station coordinates. Does NOT establish which specific point source caused these levels.")

        elif tool_name == "geocode_location":
            if isinstance(data, dict) and data.get("latitude") is not None:
                eval_lines.append(f"[Observation Evaluation - Coordinates Verified] Resolved '{data.get('query')}' to latitude {data.get('latitude')}, longitude {data.get('longitude')}.")
                if scope_info and scope_info.get("scope_type") in ("COUNTRY", "STATE_PROVINCE"):
                    eval_lines.append(f"NOTE: The user's request is {scope_info.get('scope_type')}-level. This geocoded point is a single center point or landmark, NOT the whole {scope_info.get('scope_type').lower()}. Do not treat it as representing the entire territory.")
            else:
                eval_lines.append("[Observation Evaluation - Geocoding Failed] Location could not be resolved.")
                eval_lines.append("Strategy: If fictional or ambiguous, explain this directly without inventing coordinates.")

        elif tool_name == "create_investigation_buffer":
            rad = tool_args.get("radius_km", 2.0)
            eval_lines.append(f"[Observation Evaluation - Spatial Buffer] Created {rad} km circular investigation buffer.")
            eval_lines.append("SCIENTIFIC BOUNDARY: This is an estimated spatial search area for indexing features, NOT an atmospheric dispersion plume.")

        elif tool_name == "search_scientific_publications":
            papers = data.get("papers", []) if isinstance(data, dict) else []
            if len(papers) == 0:
                eval_lines.append("[Observation Evaluation - No Scientific Papers] 0 publications returned in Crossref for this query.")
                eval_lines.append("Note: If substance is fictional (e.g. QX-999), state that no scientific literature exists.")
            else:
                eval_lines.append(f"[Observation Evaluation - Literature Retrieved] {len(papers)} peer-reviewed papers retrieved with verified DOIs.")

        elif tool_name == "get_pollutant_intelligence":
            is_known = data.get("is_known_pollutant", True) if isinstance(data, dict) else True
            if not is_known:
                eval_lines.append("[Observation Evaluation - Unrecognized Substance] Substance is NOT recognized in criteria air pollutant databases.")
                eval_lines.append("Mandatory Rule: Clearly state that no recognized criteria pollutant exists by this name.")
            else:
                eval_lines.append("[Observation Evaluation - Pollutant Profile] Verified chemical and health standards retrieved.")

        if not eval_lines:
            eval_lines.append(f"[Observation Evaluation] Tool '{tool_name}' completed. Evaluate findings against user's original objective.")

        return "\n".join(eval_lines)

    def _evaluate_evidence_synthesis(
        self,
        collected_stations: List[Dict[str, Any]],
        collected_buffer_holder: List[Any],
        collected_sources: List[Any],
        collected_reference_points: List[Dict[str, Any]],
        collected_citations: List[Dict[str, Any]],
        tools_called: List[str],
        scope_info: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Evaluate accumulated multi-source environmental evidence,
        weigh competing source hypotheses, identify missing data,
        and assess autonomous completion / inconclusive criteria.
        """
        scope_type = scope_info.get("scope_type", "NON_SPATIAL") if scope_info else "NON_SPATIAL"
        objective_type = scope_info.get("objective_type", "MULTI_SOURCE_INVESTIGATION") if scope_info else "MULTI_SOURCE_INVESTIGATION"
        target_name = scope_info.get("target_name", "") if scope_info else ""

        location_resolved = len(collected_reference_points) > 0
        ref_name = collected_reference_points[0].get("name") if location_resolved else None

        stations_found = len(collected_stations)
        stations_with_measurements = [s for s in collected_stations if s.get("measurements")]
        has_measurements = len(stations_with_measurements) > 0

        all_measurements = []
        for s in stations_with_measurements:
            all_measurements.extend(s.get("measurements", []))

        pollutants_measured = sorted(list(set(
            m.get("parameter_name") or m.get("parameter")
            for m in all_measurements if isinstance(m, dict) and (m.get("parameter_name") or m.get("parameter"))
        )))

        sources_found = len(collected_sources)
        citations_found = len(collected_citations)

        # Hypotheses evaluation matrix
        hypotheses = {
            "traffic_emissions": {
                "hypothesis": "Vehicular / Traffic Emissions",
                "status": "SUPPORTED" if any(p.lower() in ("no2", "co", "pm2.5") for p in pollutants_measured) else "PLAUSIBLE_URBAN" if location_resolved else "PENDING_EVIDENCE",
                "evidence": "Elevated traffic combustion tracers (NO2/PM2.5) or urban transport corridor." if any(p.lower() in ("no2", "co", "pm2.5") for p in pollutants_measured) else "Awaiting localized sensor measurement."
            },
            "industrial_point_sources": {
                "hypothesis": "Industrial / Manufacturing Point Sources",
                "status": "CANDIDATE_SOURCES_LOCATED" if sources_found > 0 else "NO_INDEXED_FACILITIES_IN_RADIUS" if "find_nearby_emission_sources" in tools_called else "UNCHECKED",
                "evidence": f"{sources_found} candidate facility/facilities located via Overpass API. Proximity does NOT prove causation." if sources_found > 0 else "Zero industrial facilities indexed in OSM Overpass within queried radius (does not prove absence)." if "find_nearby_emission_sources" in tools_called else "Spatial inquiry not yet conducted."
            },
            "biomass_agricultural": {
                "hypothesis": "Biomass & Agricultural Burning",
                "status": "CONTRIBUTING_FACTOR" if any("pm2.5" in p.lower() for p in pollutants_measured) else "EVALUATED",
                "evidence": "Fine particulate matter elevated; secondary or regional transport possible." if any("pm2.5" in p.lower() for p in pollutants_measured) else "Awaiting particulate baseline."
            },
            "meteorological_inversion": {
                "hypothesis": "Boundary Layer / Thermal Inversion Trapping",
                "status": "EVALUATED",
                "evidence": "Atmospheric boundary layer trapping pollutants near surface."
            }
        }

        # Missing evidence identification based on objective
        missing = []
        if scope_type in ("LOCAL", "CITY") and not location_resolved:
            missing.append("Verified location coordinates")

        if objective_type == "EMISSION_SOURCES":
            if sources_found == 0 and "find_nearby_emission_sources" not in tools_called:
                missing.append("Nearby industrial point-source inquiry")
        elif objective_type == "AMBIENT_AIR_QUALITY":
            if stations_found == 0 and "search_air_quality_locations" not in tools_called:
                missing.append("OpenAQ monitoring station lookup")
            elif stations_found > 0 and not has_measurements:
                missing.append("Latest station sensor readings")
        else:
            # Multi-source
            if stations_found == 0 and "search_air_quality_locations" not in tools_called:
                missing.append("OpenAQ monitoring station lookup")
            elif stations_found > 0 and not has_measurements:
                missing.append("Latest station sensor readings")
            if sources_found == 0 and "find_nearby_emission_sources" not in tools_called:
                missing.append("Nearby industrial source inquiry")

        # Check staleness and conflicts across multiple stations
        all_stale = all(m.get("is_stale", False) for m in all_measurements) if all_measurements else False
        has_recent = any(not m.get("is_stale", False) for m in all_measurements) if all_measurements else False
        has_multiple_stations = len(stations_with_measurements) >= 2
        has_history = "get_sensor_hourly_measurements" in tools_called
        has_research = citations_found > 0 or any("search" in t or "wiki" in t for t in tools_called)

        # Detect conflicting pollutant concentrations between nearby stations
        has_divergence = False
        divergence_detail = ""
        if has_multiple_stations:
            pm_by_station = {}
            for s in stations_with_measurements:
                for m in s.get("measurements", []):
                    p_name = (m.get("parameter_name") or m.get("parameter") or "").lower()
                    if p_name in ("pm25", "pm2.5"):
                        pm_by_station[s["id"]] = float(m.get("value", 0))

            if len(pm_by_station) >= 2:
                vals = list(pm_by_station.values())
                min_v, max_v = min(vals), max(vals)
                if min_v > 0 and (max_v / min_v >= 2.0) and (max_v - min_v >= 15.0):
                    has_divergence = True
                    divergence_detail = f"PM2.5 diverges significantly across stations ({min_v} vs {max_v} µg/m³)."

        # Autonomous stopping criteria with differentiated scenarios
        if scope_type in ("COUNTRY", "STATE_PROVINCE") and objective_type == "EMISSION_SOURCES":
            stopping_recommendation = "SCOPE_LIMITATION_INCONCLUSIVE_OR_SAMPLED"
            guidance = (
                f"Geographic Scope Limitation: The requested scope is {scope_type.title()} ('{target_name}'). "
                "Available spatial tools operate on localized radii (up to 25 km) and cannot execute a nationwide or statewide inventory. "
                "In your final_answer: 1) Acknowledge the nationwide/statewide scope; 2) Do NOT silently substitute a single city; "
                "3) Explain tool radius limitations; 4) State that a full inventory is beyond localized tools, or label any findings as a localized sample."
            )

        elif stations_found > 0 and len(all_measurements) == 0:
            stopping_recommendation = "INSUFFICIENT_EVIDENCE_STATIONS_WITHOUT_MEASUREMENTS"
            guidance = (
                f"OpenAQ returned {stations_found} stations, but ZERO measurements. "
                "Ambient monitoring stations are NOT emission sources, and station metadata alone does not establish air quality. "
                "Retrieve latest measurements or report that current measurement data is unavailable."
            )

        elif objective_type == "EMISSION_SOURCES" and "find_nearby_emission_sources" in tools_called and sources_found == 0:
            stopping_recommendation = "INCONCLUSIVE_NO_INDEXED_SOURCES"
            guidance = (
                "Zero candidate emission facilities returned from OpenStreetMap within the search radius. "
                "CRITICAL: This DOES NOT prove that zero emission sources exist. "
                "Declare in your final_answer that no industrial facilities are indexed in OSM in this radius, and the search is inconclusive."
            )

        elif has_divergence:
            stopping_recommendation = "CONFLICTING_EVIDENCE_INVESTIGATE"
            guidance = f"Conflicting evidence: {divergence_detail} Investigate nearby emission sources or local land use to explain localized gradient rather than assuming uniform concentration."

        elif stations_found > 0 and (all_stale and not has_history and len(tools_called) < 4):
            stopping_recommendation = "INSUFFICIENT_EVIDENCE_STALE_OR_MISSING"
            guidance = "Insufficient evidence: Station observations are stale (>24h). Retrieve historical measurements or query additional stations before declaring real-time air quality."

        elif objective_type == "EMISSION_SOURCES" and sources_found > 0 and location_resolved:
            stopping_recommendation = "SUFFICIENT_EVIDENCE_FOR_FINAL"
            guidance = (
                f"Identified {sources_found} candidate industrial facility/facilities near {ref_name}. "
                "Formulate final_answer synthesizing candidate sources, explaining that proximity does NOT prove causation, "
                "and noting that candidate facilities require emission verification."
            )

        elif has_measurements and location_resolved and (has_multiple_stations or has_research or len(tools_called) >= 3):
            stopping_recommendation = "SUFFICIENT_EVIDENCE_FOR_FINAL"
            guidance = "Sufficient multi-source evidence assembled. Formulate comprehensive final answer synthesizing verified measurements, emission sources, and citing authentic literature."

        elif len(tools_called) >= 3 and not has_measurements and sources_found == 0 and citations_found == 0:
            stopping_recommendation = "INCONCLUSIVE_ALL_SEARCHES_EXHAUSTED"
            guidance = "Available searches have been exhausted without verifying authentic data. Formulate final_answer declaring findings INCONCLUSIVE rather than inventing a successful conclusion."

        elif "search_air_quality_locations" in tools_called and stations_found == 0:
            stopping_recommendation = "INCONCLUSIVE_NO_STATIONS"
            guidance = "No active OpenAQ monitoring stations found within 25km radius. Formulate final answer declaring findings INCONCLUSIVE regarding real-time concentration rather than fabricating readings."

        elif len(tools_called) >= 4:
            stopping_recommendation = "BUDGET_REACHED_SYNTHESIZE"
            guidance = "Multi-source evidence collection budget reached. Synthesize findings with honest uncertainty disclosure."

        else:
            stopping_recommendation = "CONTINUE_INVESTIGATION"
            guidance = f"Proceed with next tool to resolve missing evidence: {', '.join(missing) if missing else 'literature or pollutant profile'}."

        return {
            "location_resolved": location_resolved,
            "target_location": ref_name,
            "stations_count": stations_found,
            "measurements_retrieved": len(all_measurements),
            "pollutants_detected": pollutants_measured,
            "emission_sources_count": sources_found,
            "citations_count": citations_found,
            "hypotheses": hypotheses,
            "missing_evidence": missing,
            "stopping_recommendation": stopping_recommendation,
            "guidance": guidance
        }

    def _harvest_artifacts(
        self,
        tool_name: str,
        tool_args: Dict[str, Any],
        raw_res: str,
        stations: List[Dict[str, Any]],
        buffer_holder: List[Any],
        sources: List[Any],
        reference_points: List[Dict[str, Any]],
        citations: List[Dict[str, Any]]
    ):
        """Harvest real data objects for map rendering and citation inspection."""
        try:
            data = json.loads(raw_res)
        except Exception:
            return

        if tool_name == "get_station_latest_measurements" and isinstance(data, dict):
            coords = data.get("coordinates")
            if coords:
                stations.append({
                    "id": data.get("station_id"),
                    "name": data.get("station_name"),
                    "coordinates": coords,
                    "measurements": data.get("measurements", [])
                })

        elif tool_name == "search_air_quality_locations":
            st_list = []
            if isinstance(data, dict):
                st_list = data.get("stations", [])
            elif isinstance(data, list):
                st_list = data
            for st in st_list:
                coords = st.get("coordinates")
                if coords:
                    stations.append({
                        "id": st.get("id"),
                        "name": st.get("name"),
                        "coordinates": coords,
                        "measurements": []
                    })

        elif tool_name == "geocode_location" and isinstance(data, dict):
            lat = data.get("latitude")
            lon = data.get("longitude")
            name = data.get("display_name") or tool_args.get("location_name")
            if lat and lon:
                reference_points.append({
                    "latitude": lat,
                    "longitude": lon,
                    "name": name,
                    "source": "OpenStreetMap Nominatim"
                })

        elif tool_name == "create_investigation_buffer" and isinstance(data, dict):
            from schemas.geospatial import InvestigationBuffer
            try:
                buffer_holder[0] = InvestigationBuffer(**data)
            except Exception:
                pass

        elif tool_name == "find_nearby_emission_sources":
            from schemas.geospatial import EmissionSource
            source_items = data if isinstance(data, list) else (data.get("sources", []) if isinstance(data, dict) else [])
            for src in source_items:
                if isinstance(src, dict):
                    try:
                        sources.append(EmissionSource(**src))
                    except Exception:
                        pass

        elif tool_name == "search_scientific_publications" and isinstance(data, dict):
            papers = data.get("papers", [])
            for p in papers:
                citations.append({
                    "doi": p.get("doi"),
                    "title": p.get("title"),
                    "authors": p.get("authors", []),
                    "year": p.get("publication_year"),
                    "journal": p.get("journal"),
                    "url": p.get("url")
                })

        elif tool_name in ("search_wikipedia", "get_wikipedia_summary"):
            if isinstance(data, dict):
                title = data.get("title")
                url = data.get("url")
                if title:
                    citations.append({
                        "doi": None,
                        "title": f"Wikipedia: {title}",
                        "authors": ["Wikipedia Contributors"],
                        "year": "2026",
                        "journal": "Wikipedia, The Free Encyclopedia",
                        "url": url or f"https://en.wikipedia.org/wiki/{title.replace(' ', '_')}"
                    })

